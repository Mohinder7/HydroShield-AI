"""
train_model.py
==============
Reproducible training script for the HydroShield AI GEE-based Random Forest.

Usage
-----
    python train_model.py

Or with explicit paths:
    python train_model.py \\
        --features  D:/path/to/patna_s1_features_aug2026.tif \\
        --mask      D:/path/to/patna_flood_candidates_aug2026.tif \\
        --out-dir   EPICS--main/weights

Expected inputs
---------------
Feature raster  : 6-band GeoTIFF exported from Google Earth Engine.
                  Bands must be in this exact order:
                    1  beforeVV
                    2  afterVV
                    3  beforeVH
                    4  afterVH
                    5  vvChange
                    6  vhChange
                  Values are in dB (log scale).
                  CRS: EPSG:32645  (or any projected CRS — recorded in metadata).
                  Expected ~3348 × 2262 pixels, Float32, some NaN pixels.

Candidate mask  : 1-band GeoTIFF, binary (0 = non-candidate, 1 = candidate).
                  May differ slightly in pixel dimensions from the feature raster.
                  Aligned using geospatial transforms — NOT by array resizing.

Outputs
-------
weights/random_forest_model.joblib  — trained RandomForestClassifier
weights/scaler.joblib               — fitted StandardScaler
model_meta.json                     — updated metadata with training date and stats

Label warning
-------------
The candidate mask is generated by threshold-based change detection in GEE.
These are PROVISIONAL FLOOD CANDIDATES, not independently verified ground truth.
Model outputs must be labelled "flood-candidate pixels", never "confirmed flooding".
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import joblib
import numpy as np
import rasterio
import rasterio.warp
import rasterio.windows
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split
from sklearn.metrics import (
    accuracy_score, f1_score, jaccard_score,
    precision_score, recall_score,
)
from sklearn.preprocessing import StandardScaler

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s  %(levelname)-8s  %(message)s",
    datefmt="%H:%M:%S",
)
log = logging.getLogger(__name__)

# ── constants ──────────────────────────────────────────────────────────────────
FEATURE_NAMES    = ["beforeVV", "afterVV", "beforeVH", "afterVH", "vvChange", "vhChange"]
N_FEATURES       = len(FEATURE_NAMES)
MAX_TRAIN_PIXELS = 200_000     # stratified cap — keeps training tractable
TILE_ROWS        = 256         # row-block size for tiled reading
RANDOM_STATE     = 42

_ROOT = Path(__file__).resolve().parent   # EPICS--main/


# ══════════════════════════════════════════════════════════════════════════════
#  PATH RESOLUTION
# ══════════════════════════════════════════════════════════════════════════════

def _find_file(env_var: str, well_known: list[Path], label: str) -> Path:
    """Resolve a file from env var first, then well-known locations."""
    env_val = os.getenv(env_var, "")
    if env_val:
        p = Path(env_val)
        if p.is_file():
            return p
        log.warning("%s set to '%s' but file not found.", env_var, env_val)

    for p in well_known:
        if p.is_file():
            log.info("Found %s at: %s", label, p)
            return p

    raise FileNotFoundError(
        f"{label} not found.\n"
        f"Set the {env_var} environment variable to its absolute path, or\n"
        f"place the file in one of:\n" +
        "\n".join(f"  {p}" for p in well_known)
    )


def resolve_feature_raster(cli_path: str | None) -> Path:
    if cli_path:
        p = Path(cli_path)
        if not p.is_file():
            raise FileNotFoundError(f"Feature raster not found: {p}")
        return p
    return _find_file(
        "HYDROSHIELD_FEATURE_RASTER",
        [
            _ROOT / "datasets" / "patna_s1_features_aug2026.tif",
            _ROOT.parent / "datasets" / "patna_s1_features_aug2026.tif",
            _ROOT / "data" / "patna_s1_features_aug2026.tif",
        ],
        "feature raster (patna_s1_features_aug2026.tif)",
    )


def resolve_mask_raster(cli_path: str | None) -> Path:
    if cli_path:
        p = Path(cli_path)
        if not p.is_file():
            raise FileNotFoundError(f"Candidate mask not found: {p}")
        return p
    return _find_file(
        "HYDROSHIELD_MASK_RASTER",
        [
            _ROOT / "datasets" / "patna_flood_candidates_aug2026.tif",
            _ROOT.parent / "datasets" / "patna_flood_candidates_aug2026.tif",
            _ROOT / "data" / "patna_flood_candidates_aug2026.tif",
        ],
        "candidate mask (patna_flood_candidates_aug2026.tif)",
    )


# ══════════════════════════════════════════════════════════════════════════════
#  RASTER VALIDATION
# ══════════════════════════════════════════════════════════════════════════════

def validate_feature_raster(path: Path) -> dict:
    with rasterio.open(path) as src:
        if src.count != N_FEATURES:
            raise ValueError(
                f"Feature raster has {src.count} bands; expected {N_FEATURES} "
                f"({FEATURE_NAMES})."
            )
        log.info(
            "Feature raster: %d×%d px, %d bands, CRS=%s",
            src.width, src.height, src.count, src.crs,
        )
        return {
            "width": src.width, "height": src.height,
            "crs": str(src.crs), "transform": src.transform,
            "nodata": src.nodata,
        }


def validate_mask_raster(path: Path) -> dict:
    with rasterio.open(path) as src:
        if src.count != 1:
            raise ValueError(
                f"Mask raster has {src.count} bands; expected 1."
            )
        log.info(
            "Mask raster: %d×%d px, CRS=%s",
            src.width, src.height, src.crs,
        )
        return {
            "width": src.width, "height": src.height,
            "crs": str(src.crs), "transform": src.transform,
            "nodata": src.nodata,
        }


# ══════════════════════════════════════════════════════════════════════════════
#  ALIGNED MASK READING
#  The mask may differ in dimensions — use geospatial reproject_match semantics
#  via rasterio.warp.reproject to align it to the feature raster grid.
# ══════════════════════════════════════════════════════════════════════════════

def load_aligned_mask(
    mask_path: Path,
    feat_width: int,
    feat_height: int,
    feat_transform,
    feat_crs,
) -> np.ndarray:
    """
    Read and reproject the candidate mask onto the feature raster grid.

    Returns a (H, W) uint8 array.  Invalid pixels (nodata / outside extent)
    are set to 255 and excluded from training.
    """
    with rasterio.open(mask_path) as src:
        mask_arr = np.full((feat_height, feat_width), 255, dtype="uint8")
        rasterio.warp.reproject(
            source=rasterio.band(src, 1),
            destination=mask_arr,
            src_transform=src.transform,
            src_crs=src.crs,
            dst_transform=feat_transform,
            dst_crs=feat_crs,
            resampling=rasterio.enums.Resampling.nearest,
            dst_nodata=255,
        )
    unique_vals = np.unique(mask_arr[mask_arr != 255])
    log.info("Aligned mask unique values (excl. nodata): %s", unique_vals)
    return mask_arr


# ══════════════════════════════════════════════════════════════════════════════
#  TILED FEATURE + LABEL READING
# ══════════════════════════════════════════════════════════════════════════════

def load_features_and_labels(
    feat_path: Path,
    mask_arr: np.ndarray,     # already aligned, (H, W)
    tile_rows: int = TILE_ROWS,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Stream the feature raster in tiles and collect (x, y) arrays for valid
    labelled pixels.

    Returns
    -------
    x : (N, 6) float32  — feature matrix
    y : (N,)   uint8    — labels (0 or 1)
    """
    x_chunks: list[np.ndarray] = []
    y_chunks: list[np.ndarray] = []

    with rasterio.open(feat_path) as src:
        H, W = src.height, src.width
        for row_off in range(0, H, tile_rows):
            rows = min(tile_rows, H - row_off)
            win  = rasterio.windows.Window(0, row_off, W, rows)

            # Read 6 bands → (6, rows, W) → float32
            tile = src.read(
                list(range(1, N_FEATURES + 1)),
                window=win,
                masked=True,
            ).astype("float32")
            tile_arr = tile.filled(np.nan)   # (6, rows, W)

            # Corresponding mask slice
            label_slice = mask_arr[row_off: row_off + rows, :]  # (rows, W)

            # pixels valid = all 6 features finite AND label is 0 or 1
            pixels = tile_arr.transpose(1, 2, 0).reshape(-1, N_FEATURES)  # (rows*W, 6)
            labels_flat = label_slice.ravel()                              # (rows*W,)

            feat_valid  = np.isfinite(pixels).all(axis=1)
            label_valid = np.isin(labels_flat, [0, 1])
            keep        = feat_valid & label_valid

            if keep.any():
                x_chunks.append(pixels[keep])
                y_chunks.append(labels_flat[keep].astype("uint8"))

    if not x_chunks:
        raise ValueError(
            "No valid labelled pixels found. Check that the feature raster "
            "and candidate mask overlap spatially."
        )

    x = np.concatenate(x_chunks, axis=0)
    y = np.concatenate(y_chunks, axis=0)
    log.info(
        "Collected %d valid labelled pixels (class 0: %d, class 1: %d)",
        len(y), int((y == 0).sum()), int((y == 1).sum()),
    )
    return x, y


# ══════════════════════════════════════════════════════════════════════════════
#  STRATIFIED SUB-SAMPLE
# ══════════════════════════════════════════════════════════════════════════════

def stratified_subsample(
    x: np.ndarray,
    y: np.ndarray,
    max_n: int = MAX_TRAIN_PIXELS,
    rng_seed: int = RANDOM_STATE,
) -> tuple[np.ndarray, np.ndarray]:
    if len(y) <= max_n:
        return x, y
    rng = np.random.default_rng(rng_seed)
    indices: list[np.ndarray] = []
    for cls in np.unique(y):
        cls_idx = np.where(y == cls)[0]
        n_take  = max(2, int(max_n * len(cls_idx) / len(y)))
        chosen  = rng.choice(cls_idx, size=min(n_take, len(cls_idx)), replace=False)
        indices.append(chosen)
    idx = np.concatenate(indices)
    rng.shuffle(idx)
    log.info("Sub-sampled to %d pixels (was %d).", len(idx), len(y))
    return x[idx], y[idx]


# ══════════════════════════════════════════════════════════════════════════════
#  MAIN TRAINING ROUTINE
# ══════════════════════════════════════════════════════════════════════════════

def train(feat_path: Path, mask_path: Path, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)

    # ── Validate inputs ────────────────────────────────────────────────────
    feat_meta = validate_feature_raster(feat_path)
    _          = validate_mask_raster(mask_path)

    # ── Load and align mask ────────────────────────────────────────────────
    log.info("Aligning candidate mask to feature raster grid…")
    mask_arr = load_aligned_mask(
        mask_path,
        feat_meta["width"],
        feat_meta["height"],
        feat_meta["transform"],
        feat_meta["crs"],
    )

    # ── Guard: need both classes ───────────────────────────────────────────
    unique_labels = np.unique(mask_arr[mask_arr != 255])
    if len(unique_labels) < 2 or not set(unique_labels).issuperset({0, 1}):
        raise ValueError(
            f"Candidate mask contains only classes {unique_labels}; "
            "need both 0 (non-candidate) and 1 (candidate)."
        )

    # ── Collect features and labels ────────────────────────────────────────
    log.info("Streaming features from raster…")
    x, y = load_features_and_labels(feat_path, mask_arr)

    # ── Stratified sub-sample ──────────────────────────────────────────────
    x, y = stratified_subsample(x, y)

    # ── Scale ──────────────────────────────────────────────────────────────
    log.info("Fitting StandardScaler…")
    scaler = StandardScaler()
    x_scaled = scaler.fit_transform(x)

    # ── Train / test split ─────────────────────────────────────────────────
    x_train, x_test, y_train, y_test = train_test_split(
        x_scaled, y,
        test_size=0.20,
        random_state=RANDOM_STATE,
        stratify=y,
    )
    log.info("Train: %d  Test: %d", len(y_train), len(y_test))

    # ── Train RF ───────────────────────────────────────────────────────────
    log.info("Training RandomForestClassifier (100 trees)…")
    model = RandomForestClassifier(
        n_estimators=100,
        class_weight="balanced",
        random_state=RANDOM_STATE,
        n_jobs=-1,
    )
    model.fit(x_train, y_train)

    # ── Evaluate ───────────────────────────────────────────────────────────
    preds = model.predict(x_test)
    metrics = {
        "accuracy":     round(float(accuracy_score(y_test, preds)),  4),
        "precision":    round(float(precision_score(y_test, preds, zero_division=0)), 4),
        "recall":       round(float(recall_score(y_test, preds, zero_division=0)),    4),
        "f1":           round(float(f1_score(y_test, preds, zero_division=0)),        4),
        "iou":          round(float(jaccard_score(y_test, preds, zero_division=0)),   4),
        "train_pixels": len(y_train),
        "test_pixels":  len(y_test),
    }
    log.info("Metrics: %s", metrics)

    # ── Save artifacts ─────────────────────────────────────────────────────
    model_out  = out_dir / "random_forest_model.joblib"
    scaler_out = out_dir / "scaler.joblib"
    joblib.dump(model,  model_out)
    joblib.dump(scaler, scaler_out)
    log.info("Saved model  → %s", model_out)
    log.info("Saved scaler → %s", scaler_out)

    # ── Update model_meta.json ─────────────────────────────────────────────
    meta_path = _ROOT / "model_meta.json"
    if meta_path.is_file():
        with open(meta_path, encoding="utf-8") as fh:
            meta = json.load(fh)
    else:
        meta = {}

    meta.update({
        "model_version":  "1.0.0",
        "training_date":  datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "algorithm":      "RandomForestClassifier",
        "n_estimators":   100,
        "random_state":   RANDOM_STATE,
        "class_weight":   "balanced",
        "scaler":         "StandardScaler",
        "feature_names":  FEATURE_NAMES,
        "classes":        {"0": "non-candidate", "1": "flood-candidate"},
        "holdout_metrics": metrics,
        "training_data": {
            "feature_raster": str(feat_path),
            "mask_raster":    str(mask_path),
            "n_features":     N_FEATURES,
        },
        "label_warning": (
            "Training labels are threshold-generated flood candidates derived from "
            "Sentinel-1 SAR backscatter change detection via Google Earth Engine. "
            "They are NOT independently verified flood ground truth. "
            "Do not treat model outputs as confirmed flooding."
        ),
    })
    with open(meta_path, "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2)
    log.info("Updated model_meta.json")

    log.info("Training complete.")
    log.info("  Accuracy:  %.4f", metrics["accuracy"])
    log.info("  F1:        %.4f", metrics["f1"])
    log.info("  Precision: %.4f", metrics["precision"])
    log.info("  Recall:    %.4f", metrics["recall"])


# ══════════════════════════════════════════════════════════════════════════════
#  ENTRY POINT
# ══════════════════════════════════════════════════════════════════════════════

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Train the HydroShield AI GEE Random Forest flood-candidate model."
    )
    parser.add_argument(
        "--features",
        default=None,
        help="Path to the 6-band GEE feature GeoTIFF (patna_s1_features_aug2026.tif). "
             "Overrides HYDROSHIELD_FEATURE_RASTER env var.",
    )
    parser.add_argument(
        "--mask",
        default=None,
        help="Path to the 1-band candidate mask GeoTIFF (patna_flood_candidates_aug2026.tif). "
             "Overrides HYDROSHIELD_MASK_RASTER env var.",
    )
    parser.add_argument(
        "--out-dir",
        default=str(_ROOT / "weights"),
        help="Directory to save model artifacts (default: weights/).",
    )
    args = parser.parse_args()

    try:
        feat_path = resolve_feature_raster(args.features)
        mask_path = resolve_mask_raster(args.mask)
    except FileNotFoundError as exc:
        log.error("%s", exc)
        sys.exit(1)

    train(feat_path, mask_path, Path(args.out_dir))


if __name__ == "__main__":
    main()
